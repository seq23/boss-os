#!/usr/bin/env node
/**
 * The repository's own duty prompts, bundled for the Worker (Builder U, 23 Oct 2026).
 *
 * A Mac duty reads its prompt from a file in scripts/ops; the Worker cannot read the repo at run
 * time, yet the employee page must show her the instructions the duty actually follows. So the
 * files are copied into one generated module. `--check` fails when the module and the files differ,
 * and tests/dutyPrompts.test.ts runs that check in `npm test`, so the page can never show a prompt
 * the job no longer reads.
 *
 *   node scripts/seed/generate-duty-prompts.mjs          # write
 *   node scripts/seed/generate-duty-prompts.mjs --check  # verify
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { DUTY_PROMPT_FILES } from "../../src/shared/boss/duties/ownerEdits.mjs";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const OUT = "src/shared/boss/duties/repoPrompts.generated.mjs";

export function render() {
  const entries = Object.entries(DUTY_PROMPT_FILES).map(([duty, path]) =>
    `  ${JSON.stringify(duty)}: { path: ${JSON.stringify(path)}, text: ${JSON.stringify(readFileSync(join(ROOT, path), "utf8"))} },`);
  return [
    "// GENERATED by scripts/seed/generate-duty-prompts.mjs from the files it names. Do not edit by hand.",
    "/** @type {Record<string, { path: string, text: string }>} */",
    "export const REPO_PROMPTS = Object.freeze({",
    ...entries,
    "});",
    "",
  ].join("\n");
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const want = render();
  if (process.argv.includes("--check")) {
    let have = "";
    try { have = readFileSync(join(ROOT, OUT), "utf8"); } catch { have = ""; }
    if (have !== want) {
      console.error(`${OUT} is out of step with the prompt files. Run: node scripts/seed/generate-duty-prompts.mjs`);
      process.exit(1);
    }
    console.log(`${OUT}: ${Object.keys(DUTY_PROMPT_FILES).length} prompt files in step.`);
  } else {
    writeFileSync(join(ROOT, OUT), want);
    console.log(`wrote ${OUT}`);
  }
}
